"""
How to load and use mine_score_model.joblib

The model expects a 12-column feature vector, IN THIS EXACT ORDER:

  0  score_t1      - score in the earlier of the 2 window years
  1  score_t2      - score in the later of the 2 window years (most recent known)
  2  star_t1       - star rating matching score_t1
  3  star_t2       - star rating matching score_t2
  4  death_t1      - death count aligned to score_t1's year
  5  death_t2      - death count aligned to score_t2's year
  6  mean_score    - mean(score_t1, score_t2)
  7  mean_star     - mean(star_t1, star_t2)
  8  mean_death    - mean(death_t1, death_t2)
  9  ec            - ec flag (0/1)
  10 fc            - fc flag (0/1)
  11 subsidiary_code - categorical code (see note below on reusing codes)

NaN is fine anywhere except column 11 -- HistGradientBoostingRegressor
handles missing values natively.

IMPORTANT: subsidiary_code was generated by pandas.Categorical() during
training, so the same string always maps to the same integer only in that
run. If you retrain later, re-derive the codes from train_score_forecast.py
rather than hardcoding numbers -- otherwise "SECL" might map to a different
code than the model was trained on.
"""

import numpy as np
import joblib

model = joblib.load("mine_score_model.joblib")

# Example: manually build one feature row (RAVINDRAKHANI NEW TECH MINE's
# score2324/score2425 window, used to produce this mine's score2526 in the
# original workflow).
example_row = np.array([[
    96.0, 99.0,     # score_t1, score_t2  (score2324, score2425)
    np.nan, np.nan, # star_t1, star_t2    (not tracked in this example)
    np.nan, np.nan, # death_t1, death_t2
    97.5, np.nan,   # mean_score, mean_star
    np.nan,         # mean_death
    1.0, np.nan,    # ec, fc
    0.0,            # subsidiary_code (placeholder -- see note above)
]])

pred = model.predict(example_row)
print("Predicted next-year score:", pred[0])

